"""Generate Python dataclasses from the ``proto`` directory using betterproto2.

Usage::

    uv run scripts/create_python_dataclasses.py OUT_DIR

The generated datamodels can be used (with minor modifications) as a wrappers for the autogenerated Python modules.
These models are not used directly because they introduce the betterproto2 dependency.
However, they provide a convenient and fast way to generate typed wrappers of the underlying autogenerated modules.
"""

import argparse
import logging
import os
import shutil
import sys
import tempfile
from importlib.resources import files
from pathlib import Path

from grpc_tools import protoc

_logger = logging.getLogger(__name__)

_PROTO_DIR = Path(__file__).resolve().parent.parent / "proto"


def compile_protos(proto_dir: Path, out_dir: Path) -> None:
    proto_files = sorted(str(p) for p in proto_dir.rglob("*.proto"))
    if not proto_files:
        raise FileNotFoundError(f"No .proto files found in {proto_dir}")

    # protoc locates the betterproto2 plugin through PATH; it lives next to this interpreter.
    os.environ["PATH"] = os.pathsep.join(
        [str(Path(sys.executable).parent), os.environ.get("PATH", "")]
    )
    # Bundled well-known types (e.g. google/protobuf/struct.proto).
    well_known_protos = files("grpc_tools") / "_proto"

    with tempfile.TemporaryDirectory() as tmp:
        args = [
            "grpc_tools.protoc",  # argv[0], ignored by protoc
            f"--proto_path={proto_dir}",
            f"--proto_path={well_known_protos}",
            f"--python_betterproto2_out={tmp}",
            *proto_files,
        ]

        _logger.debug("Running protoc with: %s", " ".join(args[1:]))
        if (ret := protoc.main(args)) != 0:
            raise RuntimeError(f"protoc failed with exit code {ret}")

        if out_dir.exists():
            _logger.info("Clearing output directory: %s", out_dir)
            shutil.rmtree(out_dir)
        shutil.copytree(tmp, out_dir)

    _logger.info("Generated dataclasses in %s", out_dir)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "out_dir", type=Path, help="Output package directory (replaced on each run)."
    )
    args = parser.parse_args()

    logging.basicConfig(
        format="[%(asctime)s | %(levelname)5s] %(message)s", level=logging.DEBUG
    )
    compile_protos(_PROTO_DIR, args.out_dir.resolve())


if __name__ == "__main__":
    main()
